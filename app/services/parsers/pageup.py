"""PageUp People Applicant Bulk Compile parser.

A bulk compile is one PDF holding many applicants, generated by PageUp. Its
structure is declared by the file itself, on a cover page that states which
attachment types were compiled and lists exactly who is included::

    PageUp People Applicant Bulk Compile
    The following document types are provided for each applicant
    Resume
    The following applicants are included in this document
    Peter Aguila
    ...
    Number of Applicants: 14

After that cover page the file repeats, once per applicant::

    <Applicant Name>
    Primary application form - ...        <- application report starts
    ...
    Total score                           <- application report's last page
    <attachment pages>                    <- the compiled attachment(s)
    <next applicant name>                 <- next packet starts

Every boundary in that shape is stated by the file, so extraction is exact:
no interior page's appearance has to be judged. Crucially the cover page is
*metadata* -- it describes the file rather than belonging to any applicant --
so it is never exported into anybody's documents.

The one thing not stated outright is which attachment is which when several
types were compiled. With a single declared type the attachment region is that
type by construction and is never divided -- the file has already answered the
question, and a resume's later pages carry enough contact details and section
headings to fool a splitter into cutting real resumes in half.

With several declared types that region holds several documents run together,
and dividing it is the parser's job. It divides on what the file states before
what a page merely looks like: an uploaded attachment's own filename, a printed
document title naming a different type, a restart of page numbering, and only
then the shape of the text. Where none of that appears the pages stay together
and, if they read as more than one declared type, go to review -- a document
the reviewer is told to check beats one silently exported under the wrong name.
"""

